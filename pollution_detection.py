def fill_categorical_nulls_by_distribution(df, col, random_state=None):
    if random_state is not None:
        np.random.seed(random_state)

    value_probs = df[col].dropna().value_counts(normalize=True)
    missing_mask = df[col].isna()

    df.loc[missing_mask, col] = np.random.choice(
        value_probs.index,
        size=missing_mask.sum(),
        p=value_probs.values
    )

    return df

