import pandas as pd
import numpy as np
from scipy.stats import f_oneway, chi2_contingency

# ----------------------------
# 1) Numeric vs Categorical
#    ANOVA + Eta Squared
# ----------------------------
def anova_association(feature, label):
    df_temp = pd.DataFrame({'feature': feature, 'label': label}).dropna()

    unique_classes = df_temp['label'].unique()
    groups = [df_temp[df_temp['label'] == cls]['feature'] for cls in unique_classes]

    # ANOVA
    f_stat, p_value = f_oneway(*groups)

    # Eta squared
    grand_mean = df_temp['feature'].mean()
    ss_between = sum(
        len(group) * (group.mean() - grand_mean) ** 2
        for group in groups
    )
    ss_total = sum((df_temp['feature'] - grand_mean) ** 2)

    eta_sq = ss_between / ss_total if ss_total != 0 else 0

    # Interpretation
    if p_value >= 0.05:
        relation = "No significant association"
    else:
        if eta_sq < 0.01:
            relation = "Negligible association"
        elif eta_sq < 0.06:
            relation = "Weak association"
        elif eta_sq < 0.14:
            relation = "Moderate association"
        else:
            relation = "Strong association"

    return f_stat, p_value, eta_sq, relation


# ----------------------------
# 2) Categorical vs Categorical
#    Chi-square + Cramér's V
# ----------------------------
def chi_squared_association(col1, col2):
    df_temp = pd.DataFrame({'col1': col1, 'col2': col2}).dropna()

    contingency_table = pd.crosstab(df_temp['col1'], df_temp['col2'])

    chi2, p_value, dof, expected = chi2_contingency(contingency_table)

    n = contingency_table.sum().sum()
    phi2 = chi2 / n
    r, k = contingency_table.shape

    phi2corr = max(0, phi2 - ((k - 1) * (r - 1)) / (n - 1))
    rcorr = r - ((r - 1) ** 2) / (n - 1)
    kcorr = k - ((k - 1) ** 2) / (n - 1)

    cramers_v = np.sqrt(phi2corr / min((rcorr - 1), (kcorr - 1))) if min((rcorr - 1), (kcorr - 1)) > 0 else 0

    # Interpretation
    if p_value >= 0.05:
        relation = "No significant association"
    else:
        if cramers_v < 0.10:
            relation = "Negligible association"
        elif cramers_v < 0.30:
            relation = "Weak association"
        elif cramers_v < 0.50:
            relation = "Moderate association"
        else:
            relation = "Strong association"

    return chi2, p_value, cramers_v, relation


# ----------------------------
# 3) Check all columns against target
# ----------------------------
def check_correlation_with_target(data, target_col):
    results = []

    for col in data.columns:
        if col == target_col:
            continue

        # numeric vs categorical target
        if pd.api.types.is_numeric_dtype(data[col]) and not pd.api.types.is_numeric_dtype(data[target_col]):
            f_stat, p_value, eta_sq, relation = anova_association(data[col], data[target_col])
            results.append({
                'Feature': col,
                'Test': 'ANOVA',
                'Statistic': f_stat,
                'P-value': p_value,
                'Strength': eta_sq,
                'Interpretation': relation
            })

        # categorical vs categorical target
        elif not pd.api.types.is_numeric_dtype(data[col]) and not pd.api.types.is_numeric_dtype(data[target_col]):
            chi2, p_value, cramers_v, relation = chi_squared_association(data[col], data[target_col])
            results.append({
                'Feature': col,
                'Test': 'Chi-Square',
                'Statistic': chi2,
                'P-value': p_value,
                'Strength': cramers_v,
                'Interpretation': relation
            })

    return pd.DataFrame(results).sort_values(by='P-value')


